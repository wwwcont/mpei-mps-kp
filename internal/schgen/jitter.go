// MakeJitter — вариации по строке-зерну (группа|вариант).
func MakeJitter(seed string, rows int) Jitter {
	h := fnv.New64a()
	h.Write([]byte(seed))
	r := rand.New(rand.NewSource(int64(h.Sum64())))
	j := Jitter{
		ShiftX:     float64(r.Intn(11)) * 2.54,   // 0…25,4
		ShiftY:     float64(r.Intn(13)-8) * 1.27, // −10,16…+5,08
		LabelFont:  []float64{1.0, 1.1}[r.Intn(2)],
		RefFont:    []float64{1.27, 1.5}[r.Intn(2)],
		NoteFont:   []float64{1.5, 1.7}[r.Intn(2)],
		LabelAtPin: r.Intn(2) == 1,
		RefLeft:    r.Intn(2) == 1,
		KbDY:       12.7,
	}
	if rows == 3 && r.Intn(2) == 1 {
		j.KbDY = 13.97
	}
	// новые признаки — после старых, чтобы не сдвигать прежние выборы
	j.JunctionD = []float64{0, 0.9, 1.2}[r.Intn(3)]
	_ = r.Intn(3) // бывший выбор толщины шины
	j.WireW = []float64{0, 0.2}[r.Intn(2)]
	// шина в 3–4 раза толще проводника (лекция ч1 с. 10; у листов с 0,45 при проводе 0,2 было лишь вдвое — проверка 09.10.2026)
	w := j.WireW
	if w == 0 {
		w = 0.1524 // толщина провода KiCad по умолчанию
	}
	j.BusW = round(w * []float64{3.5, 4}[r.Intn(2)])
	j.LabelItalic = r.Intn(2) == 1 && false // одно начертание на листе: имена выводов прямые, метки тоже (проверка 09.10.2026)
	// сдвиги отдельных блоков: «Примечание» правее не дальше, чем позволяет общий сдвиг (иначе вылезет за рамку)
	j.NoteDX = float64(r.Intn(int((33-j.ShiftX)/2.54)+1)) * 2.54
	j.NoteDY = float64(r.Intn(4)) * 2.54  // 0…7,62 вниз: выше — земля регистра индикатора, ниже — штамп
	j.DecDX = float64(r.Intn(9)-2) * 2.54 // −5,08…+15,24
	j.DecDY = float64(r.Intn(9)) * 2.54   // 0…20,32
	j.PwrDY = float64(r.Intn(3)-1) * 2.54 // −2,54…+2,54
	return j
}
